create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.set_normalized_name()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.name = trim(new.name);
  new.normalized_name = public.normalize_label(new.name);
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists user_settings_set_updated_at on public.user_settings;
create trigger user_settings_set_updated_at before update on public.user_settings
for each row execute function public.set_updated_at();

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['platforms', 'areas', 'study_types', 'note_categories']
  LOOP
    EXECUTE format('drop trigger if exists %I_set_updated_at on public.%I', table_name, table_name);
    EXECUTE format('create trigger %I_set_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name, table_name);
    EXECUTE format('drop trigger if exists %I_set_normalized_name on public.%I', table_name, table_name);
    EXECUTE format('create trigger %I_set_normalized_name before insert or update of name on public.%I for each row execute function public.set_normalized_name()', table_name, table_name);
  END LOOP;
END $$;

create or replace function public.seed_user_defaults(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_settings(user_id)
  values (target_user_id)
  on conflict (user_id) do nothing;

  insert into public.platforms(user_id, name, normalized_name, is_system)
  select target_user_id, value, public.normalize_label(value), true
  from unnest(array[
    'Fundação Bradesco', 'ENAP', 'Microsoft Learn', 'SEBRAE',
    'Cisco Networking Academy', 'Khan Academy', 'Escola Virtual.Gov', 'Outros'
  ]) as value
  on conflict do nothing;

  insert into public.areas(user_id, name, normalized_name, is_system)
  select target_user_id, value, public.normalize_label(value), true
  from unnest(array[
    'Excel', 'Pacote Office', 'Comunicação', 'Desenvolvimento Profissional',
    'Produtividade', 'Gestão de Projetos', 'Segurança e LGPD', 'Inteligência Artificial',
    'Finanças', 'Contabilidade', 'Controladoria', 'Power BI', 'Análise de Dados',
    'Banco de Dados', 'Programação', 'Automação', 'Inglês', 'Certificações'
  ]) as value
  on conflict do nothing;

  insert into public.study_types(user_id, name, normalized_name, is_system)
  select target_user_id, value, public.normalize_label(value), true
  from unnest(array['Aula', 'Revisão', 'Exercício', 'Projeto', 'Simulado', 'Leitura']) as value
  on conflict do nothing;

  insert into public.note_categories(user_id, name, normalized_name, is_system)
  select target_user_id, value, public.normalize_label(value), true
  from unnest(array['Resumo', 'Dúvida', 'Fórmula', 'Conceito', 'Exercício', 'Ideia', 'Revisão']) as value
  on conflict do nothing;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, name, avatar_url)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1), 'Usuário'),
    nullif(trim(new.raw_user_meta_data ->> 'avatar_url'), '')
  )
  on conflict (id) do update
    set name = excluded.name,
        avatar_url = coalesce(excluded.avatar_url, public.profiles.avatar_url);

  perform public.seed_user_defaults(new.id);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

