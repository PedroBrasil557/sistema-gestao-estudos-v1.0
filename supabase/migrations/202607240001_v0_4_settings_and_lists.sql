create or replace function public.normalize_label(value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select lower(
    regexp_replace(
      translate(
        trim(coalesce(value, '')),
        'áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ',
        'aaaaaeeeeiiiiooooouuuucnAAAAAEEEEIIIIOOOOOUUUUCN'
      ),
      '\s+',
      ' ',
      'g'
    )
  );
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) >= 3),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.user_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  monthly_goal_hours numeric(6,2) not null default 40 check (monthly_goal_hours > 0 and monthly_goal_hours <= 744),
  annual_certificate_goal integer not null default 12 check (annual_certificate_goal >= 0 and annual_certificate_goal <= 999),
  tracking_year integer not null default extract(year from current_date)::integer check (tracking_year between 2000 and 2100),
  consistency_days integer not null default 30 check (consistency_days between 7 and 365),
  current_course_id uuid,
  home_page text not null default 'estudos' check (home_page in ('estudos', 'cursos', 'dashboard', 'anotacoes', 'certificados')),
  timezone text not null default 'America/Sao_Paulo',
  locale text not null default 'pt-BR',
  date_format text not null default 'DD/MM/AAAA' check (date_format in ('DD/MM/AAAA', 'AAAA-MM-DD')),
  time_format text not null default '24h' check (time_format in ('24h', '12h')),
  theme text not null default 'system' check (theme in ('light', 'dark', 'system')),
  accent_color text not null default '#1768d3' check (accent_color ~ '^#[0-9A-Fa-f]{6}$'),
  interface_density text not null default 'default' check (interface_density in ('compact', 'default', 'comfortable')),
  rounding text not null default 'default' check (rounding in ('small', 'default', 'large')),
  remember_filters boolean not null default true,
  show_tips boolean not null default true,
  save_current_course boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

